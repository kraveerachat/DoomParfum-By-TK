export const MESSAGES: Record<Locale, Shape<Messages>> = { en, th };
export type Dictionary = Shape<Messages>;

/** Replaces {name} placeholders. Values are plain text; nothing is parsed as markup. */
export function format(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (whole, key: string) => (key in values ? String(values[key]) : whole));
}

export function studies(t: Dictionary, n: number): string {
  return format(n === 1 ? t.count.studyOne : t.count.studyOther, { n });
}

export function notesCount(t: Dictionary, n: number): string {
  return format(n === 1 ? t.count.noteOne : t.count.noteOther, { n });
}
