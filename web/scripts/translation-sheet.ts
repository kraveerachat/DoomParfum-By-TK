/**
 * Writes the English/Thai translation review sheet (DPT-PLAN-013 4.3) from the source dictionaries and
 * the Thai overlay, so the sheet cannot drift from the code. Usage: node scripts/translation-sheet.ts <out.md>
 */
import { writeFileSync } from "node:fs";
import { fixtures } from "../src/fixtures/data.ts";
import { thaiOverlay } from "../src/fixtures/th.ts";
import { en, th } from "../src/i18n/messages.ts";

const out = process.argv[2];
if (!out) {
  console.error("Usage: node scripts/translation-sheet.ts <out.md>");
  process.exit(2);
}
const cell = (s: string) => s.replaceAll("|", "\\|").replaceAll("\u2060", "⁠").replace(/\s+/g, " ");
const rows: string[] = [];
const walk = (a: unknown, b: unknown, path: string) => {
  if (typeof a === "string") {
    rows.push(`| \`${path}\` | ${cell(a)} | ${cell(b as string)} | draft | [ ] |`);
    return;
  }
  for (const k of Object.keys(a as object)) walk((a as Record<string, unknown>)[k], (b as Record<string, unknown>)[k], path ? `${path}.${k}` : k);
};
walk(en, th, "");

const prose: string[] = [];
const add = (id: string, field: string, source: string, text: { th: string | readonly string[]; review: string }) => {
  const thai = Array.isArray(text.th) ? text.th : [text.th as string];
  const src = source.split("\n");
  thai.forEach((t, i) => prose.push(`| \`${id}\` ${field}${thai.length > 1 ? ` ¶${i + 1}` : ""} | ${cell(src[i] ?? source)} | ${cell(t)} | ${text.review} | [ ] |`));
};
for (const f of fixtures.families) {
  const o = thaiOverlay.families[f.id];
  if (o) add(f.id, "descriptor", f.descriptor, o.descriptor);
}
for (const n of fixtures.notes) {
  const o = thaiOverlay.notes[n.id];
  if (o) add(n.id, "descriptor", n.descriptor, o.descriptor);
}
for (const p of fixtures.perfumes) {
  const o = thaiOverlay.perfumes[p.id];
  if (o && p.description.state === "known") add(p.id, "description", p.description.value, o.description);
}
for (const a of fixtures.articles) {
  const o = thaiOverlay.articles[a.id];
  if (!o) continue;
  add(a.id, "title", a.title, o.title);
  add(a.id, "excerpt", a.excerpt, o.excerpt);
  add(a.id, "body", a.body.join("\n"), o.body);
}

const untranslated = [
  ...fixtures.perfumes.map((p) => `\`${p.id}\` name "${p.name}"`),
  ...fixtures.notes.map((n) => `\`${n.id}\` "${n.label}"`),
  ...fixtures.families.map((f) => `\`${f.id}\` "${f.label}"`),
  ...fixtures.accords.map((a) => `\`${a.id}\` "${a.label}"`),
];

writeFileSync(
  out,
  `---
id: IMP-WEB-02-TRANSLATION-REVIEW
project: DoomParfum By TK
type: translation_review_sheet
status: owner-review
owner: human-owner
updated: 2026-11-26
tags: [doomparfum, localization, thai, review]
source_of_truth: "../../../../../DEVELOPMENT_WORKFLOW.md"
---

# Thai translation review sheet

Generated by \`web/scripts/translation-sheet.ts\` from \`web/src/i18n/messages.ts\` and \`web/src/fixtures/th.ts\`. Every Thai text is a **draft** editorial translation for the Owner (DPT-PLAN-013 4.3). Tick a row to accept it, or write the correction beside it; only the Owner's answer moves a text to \`reviewed\`. Reviewed fixture text also becomes searchable from English pages with a Thai query (4.5).

Glossary choices to confirm first (V11-OD-03): Top / Heart / Base = ชั้นบน / ชั้นกลาง / ชั้นฐาน (alternative ท็อปโน้ต / ฮาร์ตโน้ต / เบสโน้ต); Family = ตระกูลกลิ่น; Accords = แอคคอร์ด; Mock = จำลอง; Not supplied = ไม่ได้ระบุ; No entries = ไม่มีรายการ.

## Interface text (${rows.length})

| Key | English | Thai draft | State | Accept |
|---|---|---|---|---|
${rows.join("\n")}

## Fixture prose (${prose.length})

| Record and field | English source | Thai draft | State | Accept |
|---|---|---|---|---|
${prose.join("\n")}

## Kept in Latin on Thai pages (V11-OD-04)

Fictional proper names stay unchanged (Owner-directed). Family and accord labels also stay Latin until the Owner decides; they are marked \`lang="en"\`. ${untranslated.join("; ")}.

Paper study L is authored in Thai and keeps its Thai name and description on English pages (V11-OD-10: no English version by default).
`,
);
console.log(`${rows.length} interface rows, ${prose.length} prose rows`);
